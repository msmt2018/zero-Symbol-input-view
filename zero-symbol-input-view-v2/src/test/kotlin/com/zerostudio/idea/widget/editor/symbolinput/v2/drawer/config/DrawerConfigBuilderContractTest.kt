package com.zerostudio.idea.widget.editor.symbolinput.v2.drawer.config

import com.zerostudio.idea.widget.editor.symbolinput.v2.drawer.core.DrawerAnchorStrategies
import com.zerostudio.idea.widget.editor.symbolinput.v2.drawer.navigation.*
import com.zerostudio.idea.widget.editor.symbolinput.v2.drawer.panel.DrawerPanelContent
import com.zerostudio.idea.widget.editor.symbolinput.v2.drawer.style.*
import org.junit.Assert.*
import org.junit.Test

class DrawerConfigBuilderContractTest {
    private val panel = object : DrawerPanelContent {
        override fun createView(): android.view.View = error("Builder must retain content without creating views")
    }

    @Test fun everyBuilderSetterContributesToBuiltImmutableConfig() {
        val navigation = DrawerNavigationConfig(showIcons = true)
        val colors = DrawerColors(surface = 11, primaryText = 12, secondaryText = 13, accent = 14, outline = 15, scrim = 16)
        val dimensions = DrawerDimensions(70f, 800f, 22f, 18f, 14f, 10f, 40f, 5f)
        val typography = DrawerTypography(19f, 15f, 11f, fontFamily = "sans")
        val motion = DrawerMotion(350L, 0.65f, 700f, 5000f, false)
        val shape = DrawerShape(10f, 11f, 2f, 3f, 1f)
        val indicator = DrawerIndicatorStyle(DrawerIndicatorShape.PILL, 5f, 0.8f, 4f, 17, false)

        val config = DrawerConfig.builder()
            .setAnchorStrategy(DrawerAnchorStrategies.threeStage(0.4f, false))
            .setPresentationMode(DrawerPresentationMode.FULL_SCREEN)
            .setPeekContent(panel)
            .setExpandedContent(panel)
            .setDragEnabled(false)
            .setNestedScrollEnabled(false)
            .setEdgeToEdgeEnabled(true)
            .setDismissOnScrimTap(false)
            .setDismissOnBack(false)
            .setDragHandleEnabled(false)
            .setAccessibilityEnabled(false)
            .setNavigationConfig(navigation)
            .setNavigationEnabled(false)
            .setNavigationPlacement(DrawerNavigationPlacement.BOTTOM)
            .setNavigationIndicator(indicator)
            .setNavigationScrollable(false)
            .setNavigationShowTitles(false)
            .setStyle(DrawerStyle())
            .setThemeMode(DrawerThemeMode.LIGHT)
            .setFollowHostTheme()
            .setColors(colors)
            .setColorAttributes(DrawerColorAttributes(1, 2, 3, 4))
            .setSurfaceColor(21)
            .setPrimaryTextColor(22)
            .setSecondaryTextColor(23)
            .setAccentColor(24)
            .setOutlineColor(25)
            .setScrimColor(26)
            .setDimensions(dimensions)
            .setTypography(typography)
            .setMotion(motion)
            .setShape(shape)
            .setElevationDp(9f)
            .setScrimEnabled(false)
            .setClipContentToShape(false)
            .setPeekHeightDp(72f)
            .setExpandedMaxHeightDp(900f)
            .setCornerRadiusDp(30f)
            .setHorizontalPaddingDp(20f)
            .setVerticalPaddingDp(16f)
            .setPanelSpacingDp(12f)
            .setHandleSizeDp(44f, 6f)
            .setTitleTextSizeSp(21f)
            .setBodyTextSizeSp(16f)
            .setCaptionTextSizeSp(12f)
            .setFontFamily("monospace")
            .setCornerRadiiDp(1f, 2f, 3f, 4f)
            .setOutlineWidthDp(2f)
            .setFlingVelocityDp(800f, 5200f)
            .setSpringEnabled(true)
            .setSettleDurationMs(420L)
            .setDragResistance(0.8f)
            .build()

        assertSame(panel, config.peekContent)
        assertSame(panel, config.expandedContent)
        assertFalse(config.enableDrag)
        assertFalse(config.enableNestedScroll)
        assertTrue(config.enableEdgeToEdge)
        assertFalse(config.dismissOnScrimTap)
        assertFalse(config.dismissOnBack)
        assertFalse(config.dragHandleEnabled)
        assertFalse(config.accessibilityEnabled)
        assertEquals(DrawerPresentationMode.FULL_SCREEN, config.presentationMode)
        assertEquals(0.4f, (config.anchorStrategy as com.zerostudio.idea.widget.editor.symbolinput.v2.drawer.core.ThreeStageAnchorStrategy).halfExpandedFraction)
        assertEquals(DrawerNavigationPlacement.BOTTOM, config.navigationConfig.placement)
        assertEquals(indicator, config.navigationConfig.indicator)
        assertFalse(config.navigationConfig.enabled)
        assertFalse(config.navigationConfig.scrollable)
        assertFalse(config.navigationConfig.showTitles)
        assertEquals(DrawerThemeMode.FOLLOW_HOST, config.style.themeMode)
        assertEquals(DrawerColorAttributes(1, 2, 3, 4), config.style.colorAttributes)
        assertEquals(21, config.style.colors.surface)
        assertEquals(22, config.style.colors.primaryText)
        assertEquals(23, config.style.colors.secondaryText)
        assertEquals(24, config.style.colors.accent)
        assertEquals(25, config.style.colors.outline)
        assertEquals(26, config.style.colors.scrim)
        assertEquals(72f, config.style.dimensions.peekHeightDp)
        assertEquals(900f, config.style.dimensions.expandedMaxHeightDp)
        assertEquals(30f, config.style.dimensions.cornerRadiusDp)
        assertEquals(20f, config.style.dimensions.horizontalPaddingDp)
        assertEquals(16f, config.style.dimensions.verticalPaddingDp)
        assertEquals(12f, config.style.dimensions.panelSpacingDp)
        assertEquals(44f, config.style.dimensions.handleWidthDp)
        assertEquals(6f, config.style.dimensions.handleHeightDp)
        assertEquals(21f, config.style.typography.titleSizeSp)
        assertEquals(16f, config.style.typography.bodySizeSp)
        assertEquals(12f, config.style.typography.captionSizeSp)
        assertEquals("monospace", config.style.typography.fontFamily)
        assertEquals(DrawerShape(1f, 2f, 3f, 4f, 2f), config.style.shape)
        assertEquals(800f, config.style.motion.minimumFlingVelocityDp)
        assertEquals(5200f, config.style.motion.maximumFlingVelocityDp)
        assertTrue(config.style.motion.enableSpring)
        assertEquals(420L, config.style.motion.settleDurationMs)
        assertEquals(0.8f, config.style.motion.dragResistance)
        assertEquals(9f, config.style.elevationDp)
        assertFalse(config.style.drawScrim)
        assertFalse(config.style.clipContentToShape)
    }

    @Test fun defaultBuilderProducesUsableDefaultConfiguration() {
        val config = DrawerConfig.builder().build()
        assertTrue(config.enableDrag)
        assertTrue(config.enableNestedScroll)
        assertTrue(config.dismissOnBack)
        assertTrue(config.dismissOnScrimTap)
        assertTrue(config.dragHandleEnabled)
        assertTrue(config.accessibilityEnabled)
        assertEquals(DrawerPresentationMode.BOTTOM_SHEET, config.presentationMode)
        assertEquals("existing-height", config.anchorStrategy.id)
    }
}
